#!/usr/bin/env python3
"""Generate the frozen synthetic audio FIR coefficients using only the stdlib.

Recipe/provenance: docs/specs/FILTERED_AUDIO_20261123.md and the independent
numerical study docs/agents/continuation-20261123/w1-005.md. For L in {1,2,4},
M=48L, m=n-M, and normalized sinc(x)=sin(pi*x)/(pi*x):

    g[n] = (0.94/L) * sinc(0.94*m/L)
           * I0(9*sqrt(1-(m/M)^2)) / I0(9)
    h[n] = g[n] / sum(g), n=0,...,96L.

These are synthetic engineering constants, not instrument measurements. This
original implementation evaluates the standard mathematical series for atan,
sin and I0; it contains no copied SciPy or other third-party source. SciPy's
public firwin documentation describes the independent window-method reference:
https://docs.scipy.org/doc/scipy/reference/generated/scipy.signal.firwin.html

All mathematical work uses a fixed 80-digit Decimal context, including a Machin
formula for pi, before one rounding to Python binary64. Mirroring one half gives
exact symmetry. Hexadecimal C++ literals preserve those binary64 values exactly.
The fixed context avoids dependence on platform libm or caller decimal settings.
The generated text has no timestamp, absolute path or dependency version.

Default output is the repository header, independent of the working directory.
--check is strictly read-only and fails if the header is missing or stale.
"""
from __future__ import annotations

import argparse
from decimal import Context, Decimal, ROUND_HALF_EVEN, localcontext
import os
from pathlib import Path
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "include/rhodes/audio_filter_coefficients.hpp"
FACTORS = (1, 2, 4)
LATENCY_FRAMES = 48
DECIMAL_PRECISION = 80
SERIES_LIMIT = 512


def _atan_small(x: Decimal) -> Decimal:
    """Alternating arctangent series, used only for x=1/5 and x=1/239."""
    power = total = x
    for k in range(1, SERIES_LIMIT):
        power *= -x * x
        updated = total + power / (2 * k + 1)
        if updated == total:
            return updated
        total = updated
    raise ArithmeticError("Arctangent series did not converge")


def _pi() -> Decimal:
    return 16 * _atan_small(Decimal(1) / 5) - 4 * _atan_small(Decimal(1) / 239)


def _sinc(x: Decimal, pi: Decimal) -> Decimal:
    if not x:
        return Decimal(1)
    # Reduce sin(pi*x) using the exact rational x before multiplying by pi.
    reduced = x % 2
    if reduced > 1:
        reduced -= 2
    elif reduced < -1:
        reduced += 2
    angle = pi * reduced
    term = total = angle
    for k in range(1, SERIES_LIMIT):
        term *= -angle * angle / ((2 * k) * (2 * k + 1))
        updated = total + term
        if updated == total:
            return updated / (pi * x)
        total = updated
    raise ArithmeticError("Sine series did not converge")


def _i0(x: Decimal) -> Decimal:
    """I0(x) = sum((x*x/4)**k / (k!)**2), evaluated by term recurrence."""
    square_over_four = x * x / 4
    term = total = Decimal(1)
    for k in range(1, SERIES_LIMIT):
        term *= square_over_four / (k * k)
        updated = total + term
        if updated == total:
            return updated
        total = updated
    raise ArithmeticError("Bessel I0 series did not converge")


def generate_coefficients(factor: int) -> tuple[float, ...]:
    """Return unit-DC, exactly symmetric binary64 taps for a frozen factor."""
    if type(factor) is not int or factor not in FACTORS:
        raise ValueError("Factor must be one of the integers 1, 2, 4")
    context = Context(prec=DECIMAL_PRECISION, rounding=ROUND_HALF_EVEN)
    with localcontext(context):
        pi = _pi()
        middle = LATENCY_FRAMES * factor
        width = Decimal("0.94") / factor
        beta = Decimal(9)
        i0_beta = _i0(beta)
        half = []
        for offset in range(-middle, 1):
            position = Decimal(offset) / middle
            window = _i0(beta * (1 - position * position).sqrt()) / i0_beta
            half.append(width * _sinc(width * offset, pi) * window)
        dc = 2 * sum(half[:-1], Decimal(0)) + half[-1]
        normalized = tuple(float(value / dc) for value in half)
    return normalized + normalized[-2::-1]


def generate_header() -> str:
    """Render one deterministic ASCII C++20 header containing exact literals."""
    lines = [
        "// Generated by tools/generate_audio_filter.py; do not edit by hand.",
        "// Synthetic engineering FIR, not measured instrument parameters.",
        "// Contract: docs/specs/FILTERED_AUDIO_20261123.md; recipe: w1-005.md.",
        "// Original stdlib math: N=96L+1, beta=9, cutoff=0.47 host rate.",
        "// Unit DC normalization; exact symmetry; 48 host frames of delay.",
        "// Hexadecimal literals round-trip the generated IEEE binary64 values.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <limits>",
        "",
        "namespace rhodes::audio_filter {",
        "",
        "static_assert(std::numeric_limits<double>::is_iec559 &&",
        "              std::numeric_limits<double>::radix == 2 &&",
        "              std::numeric_limits<double>::digits == 53 &&",
        "              std::numeric_limits<double>::max_exponent == 1024,",
        '              "Audio FIR coefficients require IEEE binary64 double");',
        "",
        "inline constexpr std::size_t latency_frames = 48;",
        "inline constexpr double kaiser_beta = 9.0;",
        "inline constexpr double cutoff_host_rate = 0.47;",
    ]
    for factor in FACTORS:
        coefficients = generate_coefficients(factor)
        lines.extend(("", f"inline constexpr std::array<double, {len(coefficients)}> "
                      f"coefficients_l{factor} {{"))
        for start in range(0, len(coefficients), 3):
            lines.append("    " + ", ".join(value.hex() for value in
                                           coefficients[start:start + 3]) + ",")
        lines.append("};")
    lines.extend(("", "} // namespace rhodes::audio_filter", ""))
    return "\n".join(lines)


def write_header(output: Path, content: bytes) -> None:
    """Publish a whole file, refusing symlink destinations and missing parents."""
    if output.is_symlink():
        raise ValueError(f"Refusing symlink output: {output}")
    if output.exists() and not output.is_file():
        raise ValueError(f"Output is not a regular file: {output}")
    # No mkdir: an accidental output path must not create a new directory tree.
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(prefix=f".{output.name}.", suffix=".tmp",
                                         dir=output.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
        os.replace(temporary, output)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="output header (default: repository include/rhodes header)")
    parser.add_argument("--check", action="store_true",
                        help="reject a missing or stale header without writing files")
    args = parser.parse_args(argv)
    try:
        expected = generate_header().encode("ascii")
        if args.check:
            if args.output.read_bytes() != expected:
                print(f"Audio filter header is stale: {args.output}", file=sys.stderr)
                return 1
            print(f"Audio filter header is current: {args.output}")
        else:
            write_header(args.output, expected)
            print(f"Generated audio filter header: {args.output}")
        return 0
    except (OSError, ValueError, ArithmeticError) as exc:
        print(f"Audio filter generation failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
