#!/usr/bin/env python3
"""Record actual agent assignments and generate a review index.

This is an integrator-owned ledger, not an agent launcher or proof of model identity.
Only register an assignment after a real collaboration tool returned its task name.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "project/agent-campaign.json"
INDEX = ROOT / "docs/agents/CAMPAIGN.md"


def load_json(path: Path):
    def pairs(entries):
        result = {}
        for key, value in entries:
            if key in result:
                raise ValueError(f"duplicate JSON key {key!r}")
            result[key] = value
        return result

    def invalid(value):
        raise ValueError(f"nonfinite number {value}")

    def finite_float(value):
        number = float(value)
        if not math.isfinite(number):
            invalid(value)
        return number

    try:
        return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=pairs,
                          parse_constant=invalid, parse_float=finite_float)
    except (OSError, ValueError, RecursionError) as exc:
        raise ValueError(f"Cannot read {path}: {exc}") from exc


def atomic(path: Path, content: str) -> None:
    descriptor, temporary = tempfile.mkstemp(prefix=".campaign-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def validate(data: dict, require_complete: bool = False) -> None:
    if (type(data) is not dict or type(data.get("schema_version")) is not int or
            data["schema_version"] != 1 or type(data.get("requested_agents")) is not int or
            not 1 <= data["requested_agents"] <= 999 or type(data.get("agents")) is not list):
        raise ValueError("invalid campaign schema")
    if len(data["agents"]) > data["requested_agents"]:
        raise ValueError("more assignments than requested")
    ids, names = set(), set()
    required = {"id", "task_name", "status", "scope", "report", "report_sha256"}
    for agent in data["agents"]:
        if type(agent) is not dict or not required.issubset(agent):
            raise ValueError("invalid campaign assignment")
        identifier = agent["id"]
        if (not isinstance(identifier, str) or not re.fullmatch(r"A[0-9]{3}", identifier) or
                not 1 <= int(identifier[1:]) <= data["requested_agents"] or identifier in ids):
            raise ValueError("invalid or duplicate agent ID")
        task_name = agent["task_name"]
        if (not isinstance(task_name, str) or
                not re.fullmatch(r"/root/[a-z0-9_]+(?:/[a-z0-9_]+)*", task_name) or task_name in names):
            raise ValueError("invalid or duplicate actual task name")
        ids.add(identifier)
        names.add(task_name)
        if (agent["status"] not in ("running", "completed") or
                not isinstance(agent["scope"], str) or not agent["scope"].strip()):
            raise ValueError(f"{identifier}: invalid status or empty scope")
        expected = f"docs/agents/reviews/{identifier}.md"
        if agent["report"] != expected:
            raise ValueError(f"{identifier}: report path mismatch")
        path = ROOT / expected
        try:
            path.resolve().relative_to(ROOT.resolve())
        except (OSError, ValueError, RuntimeError) as exc:
            raise ValueError(f"{identifier}: report path escapes campaign root or cannot resolve") from exc
        if agent["status"] == "completed":
            if (not isinstance(agent["report_sha256"], str) or
                    not re.fullmatch(r"[0-9a-f]{64}", agent["report_sha256"])):
                raise ValueError(f"{identifier}: invalid report SHA256")
            if not path.is_file() or path.is_symlink():
                raise ValueError(f"{identifier}: missing regular report")
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            if digest != agent["report_sha256"]:
                raise ValueError(f"{identifier}: report changed since assignment completion")
        elif agent["report_sha256"] is not None:
            raise ValueError(f"{identifier}: running assignment must not have a report SHA256")
    if require_complete and (len(ids) != data["requested_agents"] or
                             any(a["status"] != "completed" for a in data["agents"])):
        raise ValueError("campaign is not complete")


def render(data: dict) -> str:
    completed = sum(a["status"] == "completed" for a in data["agents"])
    lines = ["# Agent campaign", "", "<!-- Generated by tools/campaign.py; edit the ledger through the tool. -->", "",
             f"Requested: **{data['requested_agents']} actual worker assignments**. Recorded: **{len(data['agents'])}**. Completed: **{completed}**.", "",
             "Workers were launched in successive batches within the available concurrency limit. Each row records an actual task name returned by the collaboration system and an immutable report. Completion means the assignment returned a report; it does not imply every finding was resolved or hardware accuracy established.", "",
             "This ledger records the repository setup campaign. It is separate from the earlier research campaign mentioned in the user-supplied brief. Future development uses the dependency-aware task workflow.", "",
             "| ID | Assignment | Status | Report |", "|---|---|---|---|"]
    for agent in sorted(data["agents"], key=lambda a: a["id"]):
        scope = agent["scope"].replace("|", "\\|").replace("\n", " ")
        report = f"[report](reviews/{agent['id']}.md)" if agent["status"] == "completed" else "pending"
        lines.append(f"| {agent['id']} | {scope} | {agent['status']} | {report} |")
    lines.extend(["", "See [review resolutions](REVIEW_RESOLUTION.md) for integration decisions and remaining limitations.", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    register = commands.add_parser("register")
    register.add_argument("id")
    register.add_argument("task_name")
    register.add_argument("scope")
    finish = commands.add_parser("complete")
    finish.add_argument("ids", nargs="+")
    check = commands.add_parser("validate")
    check.add_argument("--require-complete", action="store_true")
    sync = commands.add_parser("sync")
    sync.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        data = load_json(LEDGER)
        validate(data)
        if args.command == "register":
            data["agents"].append({"id": args.id, "task_name": args.task_name,
                                   "status": "running", "report": f"docs/agents/reviews/{args.id}.md",
                                   "report_sha256": None, "scope": args.scope})
        elif args.command == "complete":
            for identifier in args.ids:
                agent = next((a for a in data["agents"] if a["id"] == identifier), None)
                if agent is None:
                    raise ValueError(f"unknown agent: {identifier}")
                path = ROOT / agent["report"]
                if not path.is_file() or path.is_symlink():
                    raise ValueError(f"{identifier}: missing regular report")
                agent["report_sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
                agent["status"] = "completed"
        validate(data, getattr(args, "require_complete", False))
        expected = render(data)
        if args.command == "sync" and args.check:
            if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != expected:
                raise ValueError("campaign index is stale; run tools/campaign.py sync")
        elif args.command != "validate":
            if args.command in ("register", "complete"):
                atomic(LEDGER, json.dumps(data, indent=2) + "\n")
            atomic(INDEX, expected)
        print(f"Campaign valid: {sum(a['status'] == 'completed' for a in data['agents'])}/{data['requested_agents']} completed.")
        return 0
    except (OSError, ValueError, KeyError, TypeError, RecursionError) as exc:
        print(f"Campaign error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
